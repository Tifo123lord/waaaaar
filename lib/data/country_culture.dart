/// Cultural profile of each nation: national emblem, landmark photography and
/// identity facts (currency, language, dish, animal, motto).
///
/// Images are bundled assets:
/// - `assets/flags/<id>.png`     national flag (flagcdn, public domain)
/// - `assets/emblems/<id>.png`   coat of arms / national emblem
/// - `assets/landmarks/<id>_N.jpg` landmark photos (Wikimedia Commons)
class Landmark {
  const Landmark(this.asset, this.nameEn, this.nameFa);

  final String asset;
  final String nameEn;
  final String nameFa;

  String name(bool fa) => fa ? nameFa : nameEn;
}

